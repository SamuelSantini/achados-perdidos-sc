-- ---------------------------------------------------------------------------
-- Tabela objetos
-- ---------------------------------------------------------------------------
create table if not exists public.objetos (
  id bigint generated by default as identity primary key,
  nome text not null,
  categoria text,
  descricao text,
  local_encontrado text not null,
  data_encontrada date not null,
  status text not null default 'disponivel',
  dono_nome text,
  dono_contato text,
  foto text,
  desenho text,
  criado_em timestamptz not null default now()
);

alter table public.objetos
  drop constraint if exists objetos_status_check;

alter table public.objetos
  add constraint objetos_status_check
  check (status in ('disponivel', 'aguardando', 'devolvido'));

alter table public.objetos
  drop constraint if exists objetos_categoria_check;

alter table public.objetos
  add constraint objetos_categoria_check
  check (
    categoria is null
    or categoria in (
      'mochila', 'garrafa', 'chaves', 'estojo',
      'roupa', 'eletronico', 'livro', 'outros'
    )
  );

comment on table public.objetos is 'Objetos encontrados (achados e perdidos)';
comment on column public.objetos.status is 'disponivel | aguardando | devolvido';
comment on column public.objetos.foto is 'Foto em data URL / base64 (opcional)';
comment on column public.objetos.desenho is 'Arte dos objetos de exemplo (opcional)';

create index if not exists objetos_status_idx on public.objetos (status);
create index if not exists objetos_data_encontrada_idx on public.objetos (data_encontrada desc);

-- ---------------------------------------------------------------------------
-- Tabela usuarios (login, senha bcrypt, papel)
-- ---------------------------------------------------------------------------
create table if not exists public.usuarios (
  login text primary key,
  senha text not null,
  papel text not null default 'usuario'
);

alter table public.usuarios
  add column if not exists papel text not null default 'usuario';

alter table public.usuarios
  drop constraint if exists usuarios_papel_check;

alter table public.usuarios
  add constraint usuarios_papel_check
  check (papel in ('admin', 'usuario'));

comment on table public.usuarios is 'Contas do app (não usa Auth nativo do Supabase)';
comment on column public.usuarios.papel is 'admin = secretaria (gerenciar); usuario = reivindicar/cadastrar';
comment on column public.usuarios.senha is 'Hash bcrypt ($2a$...); legado em texto claro é re-hasheado no login';

-- ---------------------------------------------------------------------------
-- Acesso via chave publishable/anon (backend Node usa @supabase/supabase-js)
-- Em projetos novos o RLS costuma vir ligado; sem políticas o app não lê/grava.
-- ---------------------------------------------------------------------------
alter table public.objetos enable row level security;
alter table public.usuarios enable row level security;

drop policy if exists objetos_all_anon on public.objetos;
create policy objetos_all_anon on public.objetos
  for all
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists usuarios_all_anon on public.usuarios;
create policy usuarios_all_anon on public.usuarios
  for all
  to anon, authenticated
  using (true)
  with check (true);

